"""Stage the supplied B92 economy without modifying the release package."""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'SourceData/World/economy.json'
TARGET = ROOT / 'Content/Lockdown/Data/V09/economy_b92.json'
HEADER = ROOT / 'Source/Lockdown/Private/Economy/LDB92EconomyContract.h'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = SOURCE.read_bytes().replace(b'\r\n', b'\n')
    # FCatalog's inherited digest is retained for catalog compatibility. SHA256
    # identifies the supplied bytes independently in the evidence export.
    digest = hashlib.sha256(data).hexdigest()
    md5 = hashlib.md5(data).hexdigest()
    header = ('#pragma once\n// Generated by Scripts/SyncB92Economy.py.\n'
              'namespace LDB92Contract\n{\n'
              f'    inline constexpr const TCHAR* Sha256=TEXT("{digest}");\n'
              f'    inline constexpr const TCHAR* CatalogDigest=TEXT("{md5}");\n'
              '}\n').encode()
    for path, expected in ((TARGET, data), (HEADER, header)):
        if args.check:
            if not path.exists() or path.read_bytes().replace(b'\r\n', b'\n') != expected:
                raise SystemExit(f'Stale B92 economy staging: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)
    print(f'PASS B92 economy staging: {digest}')


if __name__ == '__main__':
    main()
