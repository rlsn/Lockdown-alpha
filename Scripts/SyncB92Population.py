"""Stage the selected population/routine inputs without changing the release."""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = {}
    declarations = []
    for source, target, symbol in (('population.json', 'population_b92.json', 'Population'),
                                   ('npc_schedules.json', 'schedules_b92.json', 'Schedules')):
        data = (ROOT / 'docs/v09/data' / source).read_bytes().replace(b'\r\n', b'\n')
        outputs[ROOT / 'Content/Lockdown/Data/V09' / target] = data
        declarations.append(f'    inline constexpr const TCHAR* {symbol}=TEXT("{hashlib.md5(data).hexdigest()}");')
    outputs[ROOT / 'Source/Lockdown/Private/Population/LDB92PopulationContract.h'] = (
        '#pragma once\n// Generated by Scripts/SyncB92Population.py.\nnamespace LDB92PopulationContract\n{\n' +
        '\n'.join(declarations) + '\n}\n').encode()
    for path, data in outputs.items():
        if args.check:
            if not path.exists() or path.read_bytes().replace(b'\r\n', b'\n') != data:
                raise SystemExit(f'Stale B92 population input: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print('PASS B92 population/routine staging')


if __name__ == '__main__':
    main()
