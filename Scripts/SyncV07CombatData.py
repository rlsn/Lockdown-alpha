#!/usr/bin/env python3
"""Materialize the implemented B75 catalog; runtime never reads docs.

Use --check in validation. Rebuild/import native assets after an authorized sync.
This does not implement operations or certify gameplay.
"""
import argparse
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
data = root / 'docs/v07/data'
abilities = json.loads((data / 'abilities.json').read_text())['abilities']
items = json.loads((data / 'items.json').read_text())['items']
payload = {'schema_version':7,'milestone':'B75 complete tactical content','starter_kits':json.loads((data / 'starter_kits.json').read_text())['templates'],'abilities':abilities,'null_bell':next(row for row in items if row['id']=='null_bell')}
encoded = (json.dumps(payload, indent=2) + '\n').encode('utf-8')
target = root / 'Content/Lockdown/Data/V07/combat.json'
if args.check:
    if target.read_bytes() != encoded or hashlib.sha256(encoded).hexdigest() not in (root / 'Source/Lockdown/Private/Combat/LDTacticalContract.h').read_text():
        raise SystemExit('FAIL: staged B75 catalog differs from adopted specification')
else:
    contract = root / 'Source/Lockdown/Private/Combat/LDTacticalContract.h'
    contract.write_text('#pragma once\n// Generated by SyncV07CombatData.py from the adopted subset.\n#define LD_TACTICAL_CONTRACT_SHA TEXT("' + hashlib.sha256(encoded).hexdigest() + '")\n', encoding='utf-8')
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(encoded)
print('PASS: B75 tactical catalog SHA-256 ' + hashlib.sha256(encoded).hexdigest())
